"""Signed-URL file serving for the local storage backend."""

from __future__ import annotations

import hashlib
import hmac
import time

from django.conf import settings
from django.http import FileResponse, Http404
from django.views.decorators.http import require_http_methods

from .services import LocalStorageBackend, StorageError, storage_service


@require_http_methods(["GET"])
def protected_download(request):
    """Serve a local storage object through a short-lived signed URL.

    The signature is an HMAC over ``key|expires`` with the Django secret key,
    generated by ``LocalStorageBackend.get_download_url``. The URL is a
    bearer capability with an expiry, mirroring the R2 presigned-URL
    semantics; no session or object-level check is possible at this endpoint
    because the browser follows the redirect directly.
    """
    key = request.GET.get("key", "")
    raw_expires = request.GET.get("expires", "")
    sig = request.GET.get("sig", "")
    if not key or not raw_expires or not sig:
        raise Http404
    try:
        expires = int(raw_expires)
    except (TypeError, ValueError):
        raise Http404 from None
    if time.time() > expires:
        raise Http404
    expected = hmac.new(settings.SECRET_KEY.encode(), f"{key}|{expires}".encode(), hashlib.sha256).hexdigest()
    if not hmac.compare_digest(expected, sig):
        raise Http404
    backend = storage_service.backend
    if not isinstance(backend, LocalStorageBackend):
        raise Http404
    try:
        path = backend.resolve_path(key)
    except StorageError:
        raise Http404 from None
    if not path.is_file():
        raise Http404
    return FileResponse(path.open("rb"))
